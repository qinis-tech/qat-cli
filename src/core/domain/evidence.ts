/**
 * Evidence contracts.
 *
 * Evidence is the record of what a run produced beyond pass and fail: screenshots,
 * video, traces, captured output. These are references, never content — a reference
 * can be stored in every result without cost, whereas inlining a screenshot would make
 * the result file unreadable and unshareable.
 *
 * Paths are relative, consistent with `ProjectPaths` and `OutputConfiguration`.
 */
import type { EvidenceId, ExecutionId, IsoTimestamp } from "./primitives.js";

/**
 * Kinds of artefact QAT collects.
 *
 * A closed set, so a `switch` over it is exhaustive and a new member is a compile
 * error rather than a file that silently fails to render.
 *
 * Reports are deliberately absent. A report is generated by QAT from a result, not
 * produced by a run; giving it its own artefact type in the reporting contract keeps
 * "what happened" separate from "how it was presented".
 */
export const EvidenceType = {
  Screenshot: "screenshot",
  Video: "video",
  Trace: "trace",
  Log: "log",
} as const;

export type EvidenceType = (typeof EvidenceType)[keyof typeof EvidenceType];

/**
 * The test an artefact belongs to, where one exists.
 *
 * Recorded because the alternative is inferring it from the filename, and filenames
 * are not a contract: they are chosen by whichever framework produced them, they
 * change between framework versions, and two tests with the same title collide. A
 * consumer that needs to show "the screenshot for this failure" should not be
 * parsing paths to find it.
 */
export interface EvidenceTestReference {
  /** Path relative to the project root. */
  readonly specPath: string;
  /** Full title including describe blocks, matching `TestResult.fullTitle`. */
  readonly fullTitle: string;
}

/**
 * A pointer to one artefact on disk.
 *
 * Deliberately split from the storage record that may accompany it. A reference is
 * cheap and travels inside every `ExecutionResult`; anything larger belongs behind an
 * `EvidenceStore` call.
 */
export interface EvidenceReference {
  /** Opaque identifier. Unique within a run; never parsed by a consumer. */
  readonly evidenceId: EvidenceId;
  readonly type: EvidenceType;
  /**
   * The run this artefact belongs to.
   *
   * Redundant when the reference sits inside `ExecutionResult.evidence`, and present
   * anyway: the store is queried by execution, so the key must live on the record and
   * not only in its nesting.
   */
  readonly executionId: ExecutionId;
  readonly createdAt: IsoTimestamp;
  /**
   * Path relative to the evidence directory from `OutputConfiguration`.
   *
   * Never absolute. An absolute path embeds one machine's layout, makes a stored
   * result unreadable elsewhere, breaks reproducibility between a developer run and a
   * CI run, and is the usual route by which a username or home directory ends up in a
   * published artefact or a pasted log.
   */
  readonly relativePath: string;
  /** IANA media type, e.g. `image/png`. Lets a consumer preview or serve the file without guessing from the extension. */
  readonly mediaType?: string;
  /** Size on disk. Used for retention decisions; absent if the file could not be stat-ed when recorded. */
  readonly sizeBytes?: number;
  /** The test this artefact belongs to. Absent for run-level artefacts such as a full video. */
  readonly test?: EvidenceTestReference;
}
